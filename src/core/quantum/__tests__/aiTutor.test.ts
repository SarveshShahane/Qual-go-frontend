import { describe, it, expect } from 'vitest';
import type { CanonicalCircuit, CanonicalMoment, CanonicalOperation, Circuit } from '../../../types/circuit';
import type { AIDiagnostic, AIHint, AIRecommendation, TopicMastery } from '../../../types/ai';
import { validateCircuit } from '../validator';

describe('AI Quantum Tutor Client Integration', () => {
  const canonicalBellCircuit: CanonicalCircuit = {
    name: 'Bell State (|Φ⁺⟩)',
    qubits: 2,
    classicalBits: 2,
    moments: [
      {
        operations: [{ gate: 'H', targets: [0] }],
      },
      {
        operations: [{ gate: 'CX', targets: [1], controls: [0] }],
      },
    ],
  };

  it('validates canonical circuit generated by AI Tutor', () => {
    // Convert CanonicalCircuit to Circuit IR
    const circuit: Circuit = {
      name: canonicalBellCircuit.name || 'AI Circuit',
      qubits: canonicalBellCircuit.qubits,
      qubitLabels: ['q0', 'q1'],
      classicalBits: 2,
      classicalBitLabels: ['c0', 'c1'],
      moments: canonicalBellCircuit.moments.map((m: CanonicalMoment, mIdx: number) => ({
        id: `moment_${mIdx}`,
        operations: m.operations.map((op: CanonicalOperation, opIdx: number) => ({
          id: `op_${mIdx}_${opIdx}`,
          gate: op.gate,
          targets: op.targets,
          controls: op.controls,
          params: op.params,
        })),
      })),
    };

    const errors = validateCircuit(circuit);
    expect(errors).toHaveLength(0);
  });

  it('verifies safe circuit suggestion transformation (does not mutate directly)', () => {
    const originalCircuit: Circuit = {
      name: 'Original User Circuit',
      qubits: 1,
      qubitLabels: ['q0'],
      classicalBits: 1,
      classicalBitLabels: ['c0'],
      moments: [{ id: 'm0', operations: [] }],
    };

    // User applies suggestion explicitly
    const transformed: Circuit = {
      name: canonicalBellCircuit.name || 'AI Circuit',
      qubits: canonicalBellCircuit.qubits,
      qubitLabels: ['q0', 'q1'],
      classicalBits: 2,
      classicalBitLabels: ['c0', 'c1'],
      moments: canonicalBellCircuit.moments.map((m: CanonicalMoment, mIdx: number) => ({
        id: `moment_${mIdx}`,
        operations: m.operations.map((op: CanonicalOperation, opIdx: number) => ({
          id: `op_${mIdx}_${opIdx}`,
          gate: op.gate,
          targets: op.targets,
          controls: op.controls,
        })),
      })),
    };

    expect(transformed.qubits).toBe(2);
    expect(originalCircuit.qubits).toBe(1); // Original was preserved until applied
  });

  it('differentiates syntax errors from quantum concept violations', () => {
    const syntaxDiagnostic: AIDiagnostic = {
      severity: 'error',
      category: 'syntax',
      line: 3,
      problem: 'Undefined gate symbol',
      cause: 'qc.cnot(0, 1) is deprecated in Qiskit 2.x; cx(0, 1) is expected',
      suggested_fix: 'qc.cx(0, 1)',
    };

    const quantumConceptDiagnostic: AIDiagnostic = {
      severity: 'error',
      category: 'quantum_concept',
      problem: 'Premature Measurement Collapse',
      cause: 'Measuring qubit 0 before CNOT projects superposition state into definite |0⟩ or |1⟩',
      suggested_fix: 'Place measurements at the final step after all entanglement gates',
    };

    expect(syntaxDiagnostic.category).toBe('syntax');
    expect(quantumConceptDiagnostic.category).toBe('quantum_concept');
    expect(quantumConceptDiagnostic.cause).toContain('superposition');
  });

  it('verifies progressive hint level hierarchy (1 to 4)', () => {
    const hints: AIHint[] = [
      { level: 1, label: 'Concept Clue', content: 'Consider a gate that balances probabilities.' },
      { level: 2, label: 'Direction', content: 'Apply Hadamard on wire 0, then a controlled gate.' },
      { level: 3, label: 'Partial Solution', content: 'Use qc.h(0) followed by qc.cx(0, 1).' },
      { level: 4, label: 'Full Solution', content: 'qc.h(0); qc.cx(0, 1); qc.measure_all()' },
    ];

    expect(hints).toHaveLength(4);
    expect(hints[0].level).toBe(1);
    expect(hints[3].level).toBe(4);
    expect(hints[3].label).toBe('Full Solution');
  });

  it('calculates mastery percentages and sorts recommendations by priority', () => {
    const mastery: TopicMastery = {
      topic_id: 'superposition',
      topic_name: 'Quantum Superposition & Interference',
      score: 0.85,
      confidence: 0.9,
      status: 'mastered',
    };

    const recs: AIRecommendation[] = [
      {
        id: 'rec_2',
        title: 'Phase Kickback & Deutsch Algorithm',
        reason: 'Ready after mastering entanglement',
        target_module: 'Algorithms',
        difficulty: 'Intermediate',
        priority: 2,
      },
      {
        id: 'rec_1',
        title: 'Bell States & Entanglement',
        reason: 'Mastery of superposition unlocked 2-qubit operations',
        target_module: 'Superposition',
        difficulty: 'Beginner',
        priority: 1,
      },
    ];

    expect(Math.round(mastery.score * 100)).toBe(85);
    const sorted = [...recs].sort((a, b) => a.priority - b.priority);
    expect(sorted[0].id).toBe('rec_1');
    expect(sorted[0].priority).toBe(1);
  });
});
